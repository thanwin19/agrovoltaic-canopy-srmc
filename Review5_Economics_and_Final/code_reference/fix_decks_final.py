SUBS = [(r'^R5: Digital twin', 'Review 3: Digital twin'), (r'^R7: Economics', 'Review 5: Economics'), (r'^R5 Digital twin', 'Review 3 Digital twin'), (r'^R7 Economics and final', 'Review 5 Economics and final'),
        (r'Limits of R5', 'Limits of Review 3'), (r'\(R7\)', '(Review 5)'), (r'see R4 validation', 'see the Review 2 validation'), (r'and Blender\)', 'and the Blender ray tracer)')]
def fix_text(t):
    for a, b in SUBS: t = re.sub(a, b, t)
    return t
def fix_tf(tf):
    for p in tf.paragraphs:
        old = ''.join(r.text for r in p.runs)
        if old.startswith('!Simulated, not measured. Say this explicitly'):
            new = 'Simulated, not measured: the sensor values here are generated by the model.'
        else: new = fix_text(old)
        if new != old and p.runs:
            p.runs[0].text = new
            for r in p.runs[1:]: r.text = ''
def fix_deck(path):
    prs = Presentation(path)
    for s in prs.slides:
        for sh in s.shapes:
            if sh.has_text_frame: fix_tf(sh.text_frame)
            if getattr(sh, 'has_table', False) and sh.has_table:
                for row in sh.table.rows:
                    for c in row.cells: fix_tf(c.text_frame)
    return prs
